    /**
     * Runs the SysId Quasistatic test in the given direction for the routine
     * @param direction Direction of the SysId Quasistatic test
     * @return Command to run
     */
    public Command sysIdQuasistatic(SysIdDirection direction) {
        State state = direction == SysIdDirection.FORWARD
            ? State.QUASISTATIC_FORWARD
            : State.QUASISTATIC_REVERSE;
        Timer timer = new Timer();

        return run(coroutine -> {
            timer.restart();
            while (!timer.hasElapsed(SYSID_TIMEOUT_SECONDS)) {
                double outputVolts = direction.sign
                    * SYSID_QUASISTATIC_RAMP_VOLTS_PER_SECOND
                    * timer.get();
                setControl(translationCharacterization.withVolts(Volts.of(outputVolts)));
                logSysIdState(state);
                coroutine.yield();
            }
            stopSysId(timer);
        }).whenCanceled(() -> stopSysId(timer))
            .named("sysid-" + state.toString() + "-" + getName());
    }

    /**
     * Runs the SysId Dynamic test in the given direction for the routine
     * @param direction Direction of the SysId Dynamic test
     * @return Command to run
     */
    public Command sysIdDynamic(SysIdDirection direction) {
        State state = direction == SysIdDirection.FORWARD
            ? State.DYNAMIC_FORWARD
            : State.DYNAMIC_REVERSE;
        Timer timer = new Timer();

        return run(coroutine -> {
            timer.restart();
            while (!timer.hasElapsed(SYSID_TIMEOUT_SECONDS)) {
                setControl(
                    translationCharacterization.withVolts(
                        Volts.of(direction.sign * SYSID_DYNAMIC_STEP_VOLTS)
                    )
                );
                logSysIdState(state);
                coroutine.yield();
            }
            stopSysId(timer);
        }).whenCanceled(() -> stopSysId(timer))
            .named("sysid-" + state.toString() + "-" + getName());
    }

    private void logSysIdState(State state) {
        SignalLogger.writeString("SysIdTranslation_State", state.toString());
    }

    private void stopSysId(Timer timer) {
        setControl(translationCharacterization.withVolts(Volts.zero()));
        logSysIdState(State.NONE);
        timer.stop();
    }

    public void periodic() {
        /*
         * Periodically try to apply the operator forward direction for OperatorPerspective control.
         * If we haven't applied the operator forward direction before, then we should apply it regardless of DS state.
         * This allows us to correct the forward direction in case the robot code restarts mid-match.
         * Otherwise, only check and apply the operator forward direction if the DS is disabled.
         * This ensures driving behavior doesn't change until an explicit disable event occurs during testing.
         *
         * See the documentation of setOperatorForwardDirection for more details.
         */
        if (!hasAppliedForwardDirection || RobotState.isDisabled()) {
            MatchState.getAlliance().ifPresent(allianceColor -> {
                setOperatorForwardDirection(
                    allianceColor == Alliance.RED
                        ? RED_ALLIANCE_FORWARD_DIRECTION
                        : BLUE_ALLIANCE_FORWARD_DIRECTION
                );
                hasAppliedForwardDirection = true;
            });
        }

        deviceAlerts.report();
    }

    private void startSimThread() {
        lastSimTime = Utils.getCurrentTimeSeconds();

        /* Run simulation at a faster rate so PID gains behave more reasonably */
        simNotifier = new Notifier(() -> {
            final double currentTime = Utils.getCurrentTimeSeconds();
            double deltaTime = currentTime - lastSimTime;
            lastSimTime = currentTime;

            /* use the measured time delta, get battery voltage from WPILib */
            updateSimState(deltaTime, RobotController.getBatteryVoltage());
        });
        simNotifier.startPeriodic(SIM_LOOP_PERIOD);
    }
